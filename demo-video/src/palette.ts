// Colour schemes for the opening and closing pages. Pick one with the "palette" prop.
export type Palette = {
  label: string;
  base: string;
  bg: readonly [string, string, string];
  glow: string;
  haze: string;
  textSoft: string;
  textMuted: string;
  textFooter: string;
  chip: string;
  callSub: string;
  callFace: readonly [string, string];
  callEdge: string;
  callEdgeDark: string;
  gold: readonly [string, string, string];
  // Optional overrides; anything left out falls back to the cream-and-gold look in themeOf().
  accent?: string;
  accent2?: string;
  cta?: readonly [string, string, string];
  ctaEdge?: readonly [string, string];
  ctaText?: string;
  paper?: readonly [string, string, string];
  paperEdge?: readonly [string, string];
  paperInk?: string;
  paperLabel?: string;
  paperChip?: string;
  paperMuted?: string;
  badge?: readonly [string, string];
  note?: readonly [string, string];
  noteEdge?: readonly [string, string];
  noteLabel?: string;
  noteInk?: string;
  noteMuted?: string;
};

const classicGold = ["#FBE7B5", "#E9C06B", "#C99A45"] as const;

export const themeOf = (p: Palette) => ({
  ...p,
  accent: p.accent ?? "#F3CD81",
  accent2: p.accent2 ?? "#8FE0CE",
  cta: p.cta ?? (["#FFF0C2", "#EDC778", "#D5A44C"] as const),
  ctaEdge: p.ctaEdge ?? (["#B98C3E", "#6A4A1C"] as const),
  ctaText: p.ctaText ?? "#231C10",
  paper: p.paper ?? (["#FFFDF8", "#F6EEDF", "#EEDFC4"] as const),
  paperEdge: p.paperEdge ?? (["#E6D3AC", "#8E6C38"] as const),
  paperInk: p.paperInk ?? "#1E1B17",
  paperLabel: p.paperLabel ?? "#9A7232",
  paperChip: p.paperChip ?? "rgba(154,114,50,0.10)",
  paperMuted: p.paperMuted ?? "#7A6A55",
  badge: p.badge ?? (["#2E9D6A", "#FFFFFF"] as const),
  note: p.note ?? (["#FFF8EA", "#F1E2C6"] as const),
  noteEdge: p.noteEdge ?? (["#E2C487", "#8C6A35"] as const),
  noteLabel: p.noteLabel ?? "#9A7232",
  noteInk: p.noteInk ?? "#26221C",
  noteMuted: p.noteMuted ?? "#7A6A55",
});

export type Theme = ReturnType<typeof themeOf>;

