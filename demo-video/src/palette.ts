export const backdrop = (p: Palette, x: number, y: number) =>
  `radial-gradient(ellipse at ${x}% ${y}%, ${p.glow} 0%, transparent 42%), ` +
  `radial-gradient(ellipse at ${x + 4}% ${y + 6}%, ${p.haze} 0%, transparent 30%), ` +
  `radial-gradient(ellipse at 6% 92%, rgba(255,236,205,0.05) 0%, transparent 50%), ` +
  `linear-gradient(135deg, ${p.bg[0]} 0%, ${p.bg[1]} 55%, ${p.bg[2]} 100%)`;
